// 60종의 매뉴얼 중 대표 예시를 설정하고, 없는 코드는 입력 성향 조합으로 동적 생성 처리
function getLCSIInterpretation(code) {
  if (!code) return null;
  const normalizedCode = code.toUpperCase().trim();
  if (lcsiDatabase[normalizedCode]) {
    return lcsiDatabase[normalizedCode];
  }
  
  // 데이터베이스에 없는 코드가 오면 4요소 조합으로 해석 조합을 생성 (Fallback RAG)
  const codeChars = normalizedCode.split('');
  if (codeChars.length === 4) {
    const eOrI = codeChars[0] === 'E' ? "외향형" : "내향형";
    const sOrN = codeChars[1] === 'S' ? "감각형" : "직관형";
    const tOrF = codeChars[2] === 'T' ? "사고형" : "감정형";
    const jOrP = codeChars[3] === 'J' ? "판단형" : "인식형";
    
    return {
      code: normalizedCode,
      title: `${eOrI}-${sOrN} 성향의 균형적 조력자`,
      summary: `행동적 ${eOrI} 성향과 인지적 ${sOrN} 성향을 바탕으로 문제를 대처해 나가는 심리 코드입니다.`,
      dimension: {
        action: `${eOrI} - 대인 행동`,
        cognition: `${sOrN} - 가치 인지`,
        decision: `${tOrF} - 문제 분석`,
        lifestyle: `${jOrP} - 생활 양식`
      },
      interpretation: [
        `귀하의 행동 차원은 [${eOrI}]로서 대외적 활동과 성찰의 조화를 다루며, 인지 차원 [${sOrN}]은 현실 혹은 가능성을 탐색합니다.`,
        `의사결정 시 [${tOrF}] 성향을 사용해 관계 및 논리의 척도를 정립하고, 생활 차원 [${jOrP}]를 통해 주도성과 유연성을 다룹니다.`,
        "스트레스 시에는 과도한 생각이나 감정 과몰입이 올 수 있으니 신뢰할 만한 대화 채널을 확보하시는 것을 권장합니다.",
        "매뉴얼 정형 분석 단계에 따른 맞춤 상담을 위해 아래 대화창에 구체적인 고민 내용을 알려주시면 전문 공감 답변을 제공해 드립니다."
      ]
    };
  }
  
  return null;
}

